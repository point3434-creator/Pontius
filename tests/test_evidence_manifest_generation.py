def _approved_historical_rows() -> tuple[tuple[str, ...], ...]:
    lines = APPROVED_HISTORICAL_SEED_TABLE.strip("\n").splitlines()
    expected_header = (
        "pontius evidence historical seed review v1",
        f"normalized_sha256\t{APPROVED_ENTRIES_SHA256}",
        "columns\t" + "\t".join(HISTORICAL_ROW_FIELDS),
    )
    if tuple(lines[:3]) != expected_header:
        raise AssertionError("approved historical oracle header is malformed")
    rows = []
    for line in lines[3:]:
        fields = line.split("\t")
        if len(fields) != 8 or fields[0] != "row":
            raise AssertionError("approved historical oracle row is malformed")
        rows.append(tuple(fields[1:]))
    return tuple(rows)



